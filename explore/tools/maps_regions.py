# 다람 탐험대 지역별 고정 지도(직접 설계)
# 실행: python tools/maps_regions.py [preview] [text] [지역이름...]
#   → 검증 결과 출력 + tools/maps.json 저장(게임에 넣는 자료)
# 설계 원칙
#   · 출발 구역(A) → 수리 지점 1(다리·울타리 문) → 둘째 구역(B) → 수리 지점 2 또는 거대한 바위 → 마지막 구역(C)
#   · 절벽·숲·물로 길을 나누고, 좁은 목·갈림길·막다른 보물 자리를 둠
#   · 룬 석판 3개 중 2개 이상은 마지막 구역에 둠
