@region
def beach():
    """산호 해변 만: 왼쪽은 바다, 섬을 가르는 물길 위 부두 다리, 위쪽 모래 언덕(우물), 바위로 막힌 비밀 만"""
    m = Map('beach')
    m.frame('^'); jag(m, '#', seed=4)
