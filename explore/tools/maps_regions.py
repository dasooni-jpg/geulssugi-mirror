@region
def canyon():
    """이끼 폭포 계곡: 좁은 협곡 → 출렁다리 → 폭포 초원(우물) → 바위로 막힌 비밀 고원"""
    m = Map('canyon')
    m.frame('^')
    jag(m, '#', seed=2)
    # 강: 왼쪽 아래 끝에서 오른쪽 아래 끝까지 지그재그(화면 가운데를 가로지름)
    m.tunnel([(2, 23), (2, 21), (5, 21), (5, 18), (8, 18), (8, 15), (11, 15), (11, 12), (14, 12), (14, 9),
              (17, 9), (17, 6), (20, 6), (20, 3), (23, 3)], '~')
    # 협곡 벽: 강 아래쪽은 가운데 골짜기만 남기고 양옆이 절벽
    for x, y in m.cells():
        s, d = x + y, x - y
        if s >= 26 and m.get(x, y) == '.':
            off = -1 if 30 <= s <= 35 else 0
            if abs(d - off) > 4:
                m.set(x, y, '^' if abs(d - off) > 6 else '#')
    # 왼쪽 동굴(막다른 보물 자리)
    m.sdisc('.', 33, -9, 1.9, set('#^'))
    m.tunnel([(13, 18), (13, 19), (12, 19), (12, 20)])
    # 오른쪽 폭포 웅덩이(룬)
    m.sdisc('.', 29, 8, 1.7, set('#^'))
    m.tunnel([(17, 13), (17, 12), (18, 12), (18, 11)])
    m.disc('%', 20, 10, 1.0)
    # 위쪽 초원: 가운데 바위 언덕, 오른쪽 위 폭포 연못, 연못가 숲
    m.rect('#', 9, 9, 11, 10)
    m.put('^', (10, 9), (10, 10))
    m.disc('%', 16, 2, 1.8, set('.#'))
    m.rect('T', 13, 7, 15, 8)
    m.put('T', (16, 7), (12, 7))
    # 비밀 고원(왼쪽 위): 높은 절벽으로 두르고 거대한 바위 하나로 막음
    m.rect('^', 6, 0, 6, 12)
    m.rect('^', 0, 12, 6, 12)
    m.disc('%', 3, 6, 0.9)
    m.put('B', (6, 7))
    m.put('-', (7, 7))
    # 길
    m.path([(19, 19), (16, 16), (13, 13)])
    m.path([(12, 11), (12, 8), (11, 6), (9, 6), (8, 7), (7, 7)])
    camp(m, 19, 19)
    m.put('1', (12, 12))
    m.put('2', (11, 4))
    m.put('R', (19, 11), (2, 3), (4, 10))
    m.put('C', (12, 21), (2, 1), (20, 1), (8, 11), (13, 2))
    m.put('h', (14, 15), (15, 14), (3, 8), (5, 4))
    return m


