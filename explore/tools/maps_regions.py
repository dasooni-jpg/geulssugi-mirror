def camp(m, sx, sy):
    """출발점과 텐트(출발점 왼쪽 두 칸) 자리 비우기"""
    m.clear(sx, sy, 1.6)
    m.put('S', (sx, sy))
    m.put('A', (sx - 2, sy))


def jag(m, c, edge_len=N, seed=1, rate=3):
    """뒤쪽 테두리 안쪽 줄을 들쭉날쭉하게(산맥 느낌)"""
    for i in range(edge_len):
        if (i * 7 + seed) % 5 < rate:
            m.set(i, 1, c, set('.'))
        if (i * 11 + seed * 3) % 5 < rate:
            m.set(1, i, c, set('.'))


def zig(m, c, x, y, run=3, first='U', only=None):
    """화면을 가로지르는 지그재그 물길·벽(4방향으로 이어짐).
    위(U: y-1)와 오른쪽(R: x+1)으로 run칸씩 번갈아 가다가 지도 끝·위쪽 테두리에 닿으면 멈춤. 꺾이는 점 목록을 돌려줌"""
    pts, up, k = [(x, y)], first == 'U', 0
    runs = run if isinstance(run, (list, tuple)) else [run]
    while x < N - 1 and y > 0:
        r = runs[k % len(runs)]; k += 1
        if up:
            y = max(0, y - r)
        else:
            x = min(N - 1, x + r)
        pts.append((x, y)); up = not up
    for (ax, ay), (bx, by) in zip(pts, pts[1:]):
        for cx, cy in bres(ax, ay, bx, by):
            m.set(cx, cy, c, only)
    return pts


def zigv(m, c, x, y, run=3, first='R', stop=None, only=None):
    """화면을 위에서 아래로 가르는 지그재그(오른쪽 R: x+1, 아래 D: y+1을 번갈아). stop=(최대 x, 최대 y)"""
    sx, sy = stop or (N - 1, N - 1)
    pts, right, k = [(x, y)], first == 'R', 0
    runs = run if isinstance(run, (list, tuple)) else [run]
    while x < sx and y < sy:
        r = runs[k % len(runs)]; k += 1
        if right:
            x = min(sx, x + r)
        else:
            y = min(sy, y + r)
        pts.append((x, y)); right = not right
    for (ax, ay), (bx, by) in zip(pts, pts[1:]):
        for cx, cy in bres(ax, ay, bx, by):
            m.set(cx, cy, c, only)
    return pts


def mid(pts, k):
    """지그재그 k번째 토막의 가운데 칸(다리·울타리 문 자리)"""
    (ax, ay), (bx, by) = pts[k], pts[k + 1]
    return ((ax + bx) // 2, (ay + by) // 2)


def harden(m, src='^', dst='#'):
    """바로 뒤(화면 위쪽)에 땅이 있는 높은 절벽은 한 단 낮춤(뒤쪽 길이 덜 가려지게)"""
    g = [row[:] for row in m.g]
    for x, y in m.cells():
        if g[y][x] == src and any(m.get(x + dx, y + dy) in set(LAND) | set('SA12') for dx, dy in ((-1, 0), (0, -1))):
            m.g[y][x] = dst


