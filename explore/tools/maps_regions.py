@region
def windmill():
    """라벤더 풍차 언덕: 아래 들판 → 돌담 울타리 문 → 굽이진 계단밭 → 개울 돌다리 → 풍차 언덕 꼭대기"""
    m = Map('windmill')
    m.frame('^'); jag(m, '#', seed=3)
    w1 = zig(m, '#', 9, 23, 3, 'U')        # 계단밭 돌담
    st = zig(m, '~', 0, 13, 3, 'R')        # 개울
    m.sband('^', 17, 29, -30, -12, set('.'))
    m.sband('^', 17, 29, 12, 30, set('.'))
    m.sband('#', 23, 24, -11, 4, set('.'))  # 계단밭 안 낮은 돌담(오른쪽 틈으로 돌아 오름)
